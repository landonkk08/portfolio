// Encrypts the Secret.app message so it isn't readable in the site's source.
//
//   1. Write your message in tools/secret.local.json (copy secret.example.json).
//      That file is git-ignored: it stays on your PC and is never published.
//   2. Run:  node tools/encrypt-secret.mjs
//   3. Commit the regenerated js/secret.js.
//
// The browser decrypts the message only after the 5-click trick. The key is
// derived from SECRET_PASSPHRASE, which also has to be in js/app.js, so this
// keeps the text out of view-source and GitHub. It doesn't stop a determined
// developer who reads the code. Never put real passwords or keys in it.

import { webcrypto as crypto } from "node:crypto";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const SECRET_PASSPHRASE = "portfolio-os/secret-app/v1"; // must match js/app.js
const ITERATIONS = 150000;

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = path.join(root, "tools", "secret.local.json");
const out = path.join(root, "js", "secret.js");

if (!existsSync(src)) {
  console.error("Missing tools/secret.local.json.");
  console.error("Copy tools/secret.example.json to tools/secret.local.json, write your message, and run this again.");
  process.exit(1);
}

let secret;
try {
  secret = JSON.parse(readFileSync(src, "utf8"));
} catch (err) {
  console.error(`tools/secret.local.json isn't valid JSON: ${err.message}`);
  process.exit(1);
}
if (typeof secret.title !== "string" || !Array.isArray(secret.message) || !secret.message.every((p) => typeof p === "string")) {
  console.error('tools/secret.local.json needs { "title": "...", "message": ["paragraph", ...] }');
  process.exit(1);
}

const enc = new TextEncoder();
const b64 = (bytes) => Buffer.from(bytes).toString("base64");
const salt = crypto.getRandomValues(new Uint8Array(16));
const iv = crypto.getRandomValues(new Uint8Array(12));

const baseKey = await crypto.subtle.importKey("raw", enc.encode(SECRET_PASSPHRASE), "PBKDF2", false, ["deriveKey"]);
const key = await crypto.subtle.deriveKey(
  { name: "PBKDF2", salt, iterations: ITERATIONS, hash: "SHA-256" },
  baseKey, { name: "AES-GCM", length: 256 }, false, ["encrypt"]);
const data = await crypto.subtle.encrypt(
  { name: "AES-GCM", iv }, key,
  enc.encode(JSON.stringify({ title: secret.title, message: secret.message })));

const payload = { v: 1, iterations: ITERATIONS, salt: b64(salt), iv: b64(iv), data: b64(new Uint8Array(data)) };
writeFileSync(out,
  "/* Generated by tools/encrypt-secret.mjs. Don't edit by hand.\n" +
  "   The Secret.app message, encrypted. Edit tools/secret.local.json and re-run the script. */\n" +
  `window.PORTFOLIO_SECRET = ${JSON.stringify(payload, null, 2)};\n`);
console.log("Wrote js/secret.js");
